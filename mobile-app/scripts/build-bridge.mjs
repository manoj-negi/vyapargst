// Bundles bridge/capacitor-bridge.ts into the shared website's public/js/vendor folder.
// Run after changing the bridge or upgrading @capacitor/core: npm run bridge
import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(here, "../../public/js/vendor/capacitor-bridge.js");
const pkg = JSON.parse(await (await import("node:fs/promises")).readFile(path.resolve(here, "../node_modules/@capacitor/core/package.json"), "utf8"));

await build({
  entryPoints: [path.resolve(here, "../bridge/capacitor-bridge.ts")],
  bundle: true,
  format: "iife",
  target: ["es2019"],
  minify: true,
  legalComments: "none",
  outfile: out,
  banner: { js: `/* Generated by mobile-app (npm run bridge) from @capacitor/core ${pkg.version}. Do not edit; loaded only inside the app. */` },
});
console.log(`Wrote ${path.relative(process.cwd(), out)}`);
